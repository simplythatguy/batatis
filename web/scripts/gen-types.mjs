// Turns the engine's JSON Schema (src/api/engine.schema.json, written by `python -m engine.schema_export`)
// into src/api/types.gen.ts. Covers the subset pydantic emits for the engine models: $ref, anyOf, enum,
// const, arrays (items and fixed-length prefixItems), objects and primitives.
//   node scripts/gen-types.mjs           write types.gen.ts
//   node scripts/gen-types.mjs --check   exit 1 when types.gen.ts does not match the schema
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SCHEMA = join(here, "../src/api/engine.schema.json");
const OUT = join(here, "../src/api/types.gen.ts");

const PRIMITIVE = { string: "string", number: "number", integer: "number", boolean: "boolean", null: "null" };

function tsType(s) {
  if (s.$ref) return s.$ref.split("/").pop();
  if (s.anyOf) return [...new Set(s.anyOf.map(tsType))].join(" | ");
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.type === "array") {
    if (s.prefixItems) return `[${s.prefixItems.map(tsType).join(", ")}]`;
    const inner = s.items ? tsType(s.items) : "unknown";
    return inner.includes(" ") ? `(${inner})[]` : `${inner}[]`;
  }
  if (s.type === "object" || s.properties) {
    if (!s.properties) return s.additionalProperties ? `Record<string, ${tsType(s.additionalProperties)}>` : "Record<string, unknown>";
    return `{ ${props(s).join(" ")} }`;
  }
  if (Array.isArray(s.type)) return s.type.map((t) => PRIMITIVE[t] ?? "unknown").join(" | ");
  return PRIMITIVE[s.type] ?? "unknown";
}

function props(s) {
  const req = new Set(s.required ?? []);
  return Object.entries(s.properties).map(([k, v]) => {
    const doc = v.description ? `/** ${v.description} */ ` : "";
    return `${doc}${k}${req.has(k) ? "" : "?"}: ${tsType(v)};`;
  });
}

export function generate(schema) {
  const lines = [
    "// Generated by web/scripts/gen-types.mjs from engine.schema.json (pydantic models in engine/).",
    "// Do not edit: change the engine model, run `python -m engine.schema_export`, then `npm run gen:types`.",
    "// Fields with a default are optional here because the engine accepts them omitted; responses always carry them.",
    "",
  ];
  for (const name of Object.keys(schema.$defs).sort()) {
    const def = schema.$defs[name];
    if (def.description) lines.push(`/** ${def.description.split("\n")[0]} */`);
    if (def.properties) {
      lines.push(`export interface ${name} {`, ...props(def).map((p) => `  ${p}`), "}", "");
    } else {
      lines.push(`export type ${name} = ${tsType(def)};`, "");
    }
  }
  return lines.join("\n");
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
// Compare content, not line endings: a Windows checkout with Git's default
// core.autocrlf=true stores this file with CRLF while the generator emits LF.
const lf = (text) => text.replace(/\r\n/g, "\n");
if (isMain) {
  const text = generate(JSON.parse(readFileSync(SCHEMA, "utf8")));
  if (process.argv.includes("--check")) {
    if (!existsSync(OUT) || lf(readFileSync(OUT, "utf8")) !== lf(text)) {
      console.error("src/api/types.gen.ts is stale: run `npm run gen:types`");
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT}`);
  }
}
