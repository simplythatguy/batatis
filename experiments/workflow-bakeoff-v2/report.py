"""Write RESULTS.md and the small result files from the saved runs. Every number in RESULTS.md comes from here."""
from __future__ import annotations

import json
import shutil
import statistics as st
from collections import defaultdict

from common import HERE, RUNS, load_cases, read_json
from arms import valid_picks
from judge import CRITERIA, collect

ARM_NAMES = {
    'ours': 'Ours today (main)',
    'kaan_form': 'Kaan flowchart as a form',
    'kaan_form_lookup': 'Kaan flowchart as a form + code lookup',
    'kaan_app': "Kaan's boxes done by the app",
    'hybrid': 'Hybrid (planner + 6 draft cards)',
    'hybrid_lean': 'Hybrid lean (drafts on one screen)',
    'hybrid_focus': 'Hybrid focus (drafts, 3 gap questions)',
}
PERSONAS = {'novice': 'Novice applicant', 'expert': 'Expert with the code book', 'expert_memory': 'Expert from memory'}


def m(values, digits=1):
    values = [v for v in values if v is not None]
    return f'{st.mean(values):.{digits}f}' if values else 'n/a'


def recall_rows():
    cases = {c['id']: c for c in load_cases()}
    out = defaultdict(lambda: defaultdict(int))
    n = 0
    for case_id, case in cases.items():
        s0 = read_json(RUNS / 'stage0' / f'{case_id}.json')
        gold = case['gold']
        arms = {'product': s0['prod_rank']}
        r1 = RUNS / 'responses' / 'r1' / f'{case_id}.json'
        if r1.exists():
            arms['rerank'] = [p['id'] for p in valid_picks(case, s0, read_json(r1))]
        r1x = RUNS / 'responses' / 'r1x' / f'{case_id}.json'
        if r1x.exists():
            widened = {**s0, 'pool': read_json(RUNS / 'requests' / 'r1x' / f'{case_id}.json')['pool']}
            arms['toc_rerank'] = [p['id'] for p in valid_picks(case, widened, read_json(r1x))]
        n += 1
        for name, ranked in arms.items():
            out[name]['cases'] += 1
            out[name]['top1'] += ranked[:1] != [] and ranked[0] in gold
            out[name]['top3'] += any(g in ranked[:3] for g in gold)
            out[name]['all8'] += all(g in ranked[:8] for g in gold)
            out[name]['articles8'] += sum(g in ranked[:8] for g in gold)
            out[name]['gold'] += len(gold)
    return out


def main() -> None:
    runs = read_json(RUNS / 'results' / 'runs.json')
    summary = read_json(RUNS / 'results' / 'summary.json')
    judge = collect()
    by = defaultdict(list)
    for row in judge:
        by[(row['persona'], row['arm'])].append(row)
    lines = ['# Workflow bakeoff v2: results', '',
             f"Generated by `report.py` from the saved runs. Cases: {len({r['case'] for r in runs})} real Alberta records "
             f"(`docs/research/2026-10-23-elephant/cases-alberta.json`). Blind-graded cases: {len({r['case'] for r in judge})}.", '']
    for persona, label in PERSONAS.items():
        lines += [f'## {label}', '',
                  '| Workflow | Inputs | Expert questions | Paragraphs to write | Minutes (est.) | Forced guesses | Dead ends | '
                  'Cited article first | Article recall | Coverage (of 10) | Judge overall (of 10) | Judge admin completeness (of 5) |',
                  '|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|']
        for row in summary:
            if row['persona'] != persona:
                continue
            graded = by.get((persona, row['arm']), [])
            lines.append(f"| {ARM_NAMES[row['arm']]} | {row['inputs']:.1f} | {row['expert_inputs']:.1f} | {row['essays']:.1f} | "
                         f"{row['minutes_est']:.1f} | {row['forced_guesses']} | {row['dead_ends']} | {row['benchmark_hit']}/{row['n']} | "
                         f"{row['article_recall']:.2f} | {row['coverage_of_10']:.1f} | "
                         f"{m([g['overall'] for g in graded]) if graded else 'not graded'} | "
                         f"{m([g['admin_completeness'] for g in graded]) if graded else 'not graded'} |")
        lines.append('')
    rec = recall_rows()
    lines += ['## Code identification on the real cases', '',
              '| Ranking | Cases | Cited article first | Cited article in top 3 | Every cited article in top 8 | Cited articles in top 8 |',
              '|---|---:|---:|---:|---:|---:|']
    names = {'product': 'Product today (deterministic ledger)', 'rerank': 'Haiku 5.5 rerank of the product pool',
             'toc_rerank': 'Haiku 5.5 table-of-contents search, then rerank'}
    for key, label in names.items():
        r = rec.get(key)
        if r and r['cases']:
            lines.append(f"| {label} | {r['cases']} | {r['top1']} | {r['top3']} | {r['all8']} | {r['articles8']}/{r['gold']} |")
    lines.append('')
    if judge:
        lines += ['## Blind judge detail (Opus 5.5, medium effort)', '',
                  '| Applicant | Workflow | n | ' + ' | '.join(CRITERIA) + ' | overall | compliance-claim flags | fabrication flags |',
                  '|---|---|---:|' + '---:|' * (len(CRITERIA) + 3)]
        for (persona, arm), items in sorted(by.items()):
            lines.append(f"| {persona} | {ARM_NAMES[arm]} | {len(items)} | " + ' | '.join(m([i[c] for i in items]) for c in CRITERIA)
                         + f" | {m([i['overall'] for i in items])} | {sum(i['compliance_claim'] for i in items)} | {sum(i['fabrication'] for i in items)} |")
        lines.append('')
    (HERE / 'RESULTS.md').write_text('\n'.join(lines) + '\n')
    results = HERE / 'results'
    results.mkdir(exist_ok=True)
    for name in ('summary.json', 'summary.csv', 'identify_metrics.json'):
        if (RUNS / 'results' / name).exists():
            shutil.copy(RUNS / 'results' / name, results / name)
    (results / 'judge_scores.json').write_text(json.dumps(judge, indent=1))
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
